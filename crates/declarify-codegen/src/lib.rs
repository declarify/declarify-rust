//! Deterministic source generator for Declarify.
//!
//! Generates five of the six `src/generated/` subtrees described in
//! `docs/02-architecture.md` so far: `resources/` (concrete resource alias
//! and request/input types), `application/` (repository trait, service
//! trait, default CRUD service), `persistence/` (fresh-schema SQL +
//! `rusqlite`-backed repository), `http/` (`axum` routes/handlers), and
//! `client/` (typed async REST client). `cli/` arrives with DCL-0005; this
//! crate's `generate` will grow to emit it without changing the contract for
//! callers.
//!
//! This crate only renders file contents; it never touches the filesystem.
//! `declarify-cli` owns writing to a temp directory, running `rustfmt`, and
//! atomically swapping the real `src/generated` tree (see
//! `docs/03-declaration-and-generation.md`, "Determinism and safety").

mod application;
mod client;
mod http;
mod persistence;
mod resources;
mod util;

use std::collections::BTreeMap;
use std::path::PathBuf;

use declarify_schema::ResourceSchema;

/// Prefixed onto every generated file so a reader (or a future generation
/// run) can tell it apart from handwritten source at a glance.
pub const OWNERSHIP_MARKER: &str =
    "// @generated by declarify. DO NOT EDIT — regenerate with `declarify generate`.\n";

/// Deterministic map of file path (relative to the `src/generated/` root) to
/// rendered file contents. A `BTreeMap` keeps iteration order stable so two
/// generations from the same input are byte-identical.
pub type GeneratedTree = BTreeMap<PathBuf, String>;

/// Renders the full generated tree for the given validated resources.
///
/// Resources are expected to already be sorted by name (as
/// `declarify_schema::scan_source_root` guarantees), so output ordering is a
/// pure function of the input schema.
pub fn generate(resources: &[ResourceSchema]) -> GeneratedTree {
    let mut tree = GeneratedTree::new();
    let mut modules = Vec::with_capacity(resources.len());

    for resource in resources {
        let module = util::module_name(&resource.name);
        tree.insert(
            PathBuf::from("resources").join(format!("{module}.rs")),
            resources::render(resource),
        );
        tree.insert(
            PathBuf::from("application").join(format!("{module}.rs")),
            application::render(resource),
        );
        tree.insert(
            PathBuf::from("persistence").join(format!("{module}.rs")),
            persistence::render(resource),
        );
        tree.insert(
            PathBuf::from("http").join(format!("{module}.rs")),
            http::render(resource),
        );
        tree.insert(
            PathBuf::from("client").join(format!("{module}.rs")),
            client::render(resource),
        );
        modules.push(module);
    }

    for dir in ["resources", "application", "persistence", "http", "client"] {
        tree.insert(
            PathBuf::from(dir).join("mod.rs"),
            render_submodule_list(&modules),
        );
    }
    tree.insert(PathBuf::from("mod.rs"), render_top_level_mod());

    tree
}

fn render_submodule_list(modules: &[String]) -> String {
    let mut out = String::from(OWNERSHIP_MARKER);
    out.push('\n');
    for module in modules {
        out.push_str(&format!("pub mod {module};\n"));
    }
    out
}

fn render_top_level_mod() -> String {
    format!(
        "{OWNERSHIP_MARKER}\n\
         pub mod application;\n\
         pub mod client;\n\
         pub mod http;\n\
         pub mod persistence;\n\
         pub mod resources;\n"
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use declarify_core::Operation;
    use declarify_schema::{FieldSchema, FieldType, TypeSchema};

    fn note_schema() -> ResourceSchema {
        ResourceSchema {
            name: "Note".to_string(),
            api_version: "notes.declarify.dev/v1".to_string(),
            plural: "notes".to_string(),
            operations: Operation::ALL.to_vec(),
            spec: TypeSchema {
                name: "NoteSpec".to_string(),
                module_path: "domain::note".to_string(),
                fields: vec![
                    FieldSchema {
                        name: "title".to_string(),
                        ty: FieldType::String,
                    },
                    FieldSchema {
                        name: "body".to_string(),
                        ty: FieldType::String,
                    },
                ],
            },
            status: TypeSchema {
                name: "NoteStatus".to_string(),
                module_path: "domain::note".to_string(),
                fields: vec![FieldSchema {
                    name: "indexed".to_string(),
                    ty: FieldType::Bool,
                }],
            },
        }
    }

    #[test]
    fn generation_is_deterministic() {
        let schema = vec![note_schema()];
        assert_eq!(generate(&schema), generate(&schema));
    }

    #[test]
    fn every_generated_file_carries_the_ownership_marker() {
        let schema = vec![note_schema()];
        let tree = generate(&schema);
        assert!(!tree.is_empty());
        for (path, contents) in &tree {
            assert!(
                contents.starts_with(OWNERSHIP_MARKER),
                "{path:?} is missing the ownership marker"
            );
        }
    }

    #[test]
    fn every_subtree_is_generated_per_resource() {
        let schema = vec![note_schema()];
        let tree = generate(&schema);
        for dir in ["resources", "application", "persistence", "http", "client"] {
            assert!(
                tree.contains_key(&PathBuf::from(dir).join("note.rs")),
                "missing {dir}/note.rs"
            );
            assert!(
                tree.contains_key(&PathBuf::from(dir).join("mod.rs")),
                "missing {dir}/mod.rs"
            );
        }
        assert!(tree.contains_key(&PathBuf::from("mod.rs")));
    }

    #[test]
    fn http_file_declares_the_stable_rest_paths() {
        let schema = vec![note_schema()];
        let tree = generate(&schema);
        let http = &tree[&PathBuf::from("http/note.rs")];
        assert!(http.contains("\"/api/v1/notes\""));
        assert!(http.contains("\"/api/v1/notes/{id}\""));
        assert!(http.contains("\"/api/v1/notes/{id}/status\""));
        assert!(http.contains("StatusCode::CREATED"));
        assert!(http.contains("StatusCode::NO_CONTENT"));
        assert!(http.contains("require_if_match"));
    }

    #[test]
    fn client_file_exposes_one_method_per_enabled_operation() {
        let schema = vec![note_schema()];
        let tree = generate(&schema);
        let client = &tree[&PathBuf::from("client/note.rs")];
        assert!(client.contains("pub struct NoteClient"));
        for method in [
            "pub async fn create",
            "pub async fn get",
            "pub async fn list",
            "pub async fn replace_spec",
            "pub async fn update_status",
            "pub async fn delete",
        ] {
            assert!(client.contains(method), "missing `{method}`");
        }
        assert!(client.contains("If-Match"));
    }

    #[test]
    fn persistence_file_uses_plural_as_table_name_and_expected_columns() {
        let schema = vec![note_schema()];
        let tree = generate(&schema);
        let persistence = &tree[&PathBuf::from("persistence/note.rs")];
        assert!(persistence.contains("CREATE TABLE IF NOT EXISTS notes"));
        assert!(persistence.contains("spec_title TEXT NOT NULL"));
        assert!(persistence.contains("spec_body TEXT NOT NULL"));
        assert!(persistence.contains("status_indexed INTEGER NOT NULL"));
        assert!(persistence.contains("pub struct SqliteNoteRepository"));
        assert!(persistence.contains("impl NoteRepository for SqliteNoteRepository"));
    }
}
